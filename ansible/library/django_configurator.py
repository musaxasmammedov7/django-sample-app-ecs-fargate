#!/usr/bin/python
"""
django_configurator - Custom Ansible module.

Generates or updates the Django application's local_settings.py file
with the correct database configuration and environment-specific settings
(e.g. DEBUG, ALLOWED_HOSTS).

The module is idempotent: it only writes the file when the content changes.

Place in ansible/library/django_configurator.py
"""

from __future__ import absolute_import, division, print_function

__metaclass__ = type

import json
import os

from ansible.module_utils.basic import AnsibleModule


def build_settings_content(params):
    """Build the local_settings.py content from module parameters."""
    env = params["environment"]
    db_host = params["db_host"]
    db_port = params.get("db_port", 5432)
    db_name = params["db_name"]
    db_user = params["db_user"]
    db_password = params["db_password"]
    additional = params.get("additional_settings") or {}

    if env not in ("development", "production"):
        raise ValueError(
            "environment must be 'development' or 'production', got: {0}".format(env)
        )

    # Environment-specific defaults (safe, no credentials).
    if env == "development":
        debug = True
        allowed_hosts = ["*"]
    else:
        debug = False
        allowed_hosts = ["*"]

    # Allow override via additional_settings.
    if "DEBUG" in additional:
        debug = bool(additional["DEBUG"])
    if "ALLOWED_HOSTS" in additional:
        allowed_hosts = additional["ALLOWED_HOSTS"]

    lines = []
    lines.append("# Auto-generated by django_configurator. Do not edit manually.")
    lines.append("")
    lines.append("DEBUG = {0}".format(repr(debug)))
    lines.append("ALLOWED_HOSTS = {0}".format(repr(allowed_hosts)))
    lines.append("")
    lines.append("DATABASES = {")
    lines.append("    'default': {")
    lines.append("        'ENGINE': 'django.db.backends.postgresql',")
    lines.append("        'HOST': {0},".format(repr(db_host)))
    lines.append("        'PORT': {0},".format(repr(db_port)))
    lines.append("        'NAME': {0},".format(repr(db_name)))
    lines.append("        'USER': {0},".format(repr(db_user)))
    lines.append("        'PASSWORD': {0},".format(repr(db_password)))
    lines.append("        'CONN_MAX_AGE': 0,")
    lines.append("        'TEST': {'CHARSET': 'UTF8'},")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    # Additional arbitrary Django settings.
    for key in sorted(additional.keys()):
        if key in ("DEBUG", "ALLOWED_HOSTS", "DATABASES"):
            continue
        lines.append("{0} = {1}".format(key, repr(additional[key])))
        lines.append("")

    return "\n".join(lines)


def main():
    module = AnsibleModule(
        argument_spec={
            "environment": {"type": "str", "required": True},
            "db_host": {"type": "str", "required": True},
            "db_name": {"type": "str", "required": True},
            "db_user": {"type": "str", "required": True},
            "db_password": {"type": "str", "required": True, "no_log": True},
            "db_port": {"type": "int", "required": False, "default": 5432},
            "additional_settings": {
                "type": "dict",
                "required": False,
                "default": {},
            },
            "app_dir": {"type": "str", "required": True},
        },
        supports_check_mode=True,
    )

    params = module.params
    app_dir = params["app_dir"]

    # Locate the Django project settings.py to derive the correct location
    # for local_settings.py. Prefer <app_dir>/hc/local_settings.py.
    candidates = [
        os.path.join(app_dir, "hc", "local_settings.py"),
        os.path.join(app_dir, "local_settings.py"),
    ]
    settings_file = None
    for cand in candidates:
        if os.path.exists(os.path.dirname(cand)):
            settings_file = cand
            break

    if settings_file is None:
        module.fail_json(
            msg="Application directory {0} does not exist. "
            "Clone the code before running django_configurator.".format(app_dir)
        )

    try:
        new_content = build_settings_content(params)
    except ValueError as exc:
        module.fail_json(msg=str(exc))

    # Idempotency check: only write when the content changed.
    changed = False
    if os.path.exists(settings_file):
        try:
            with open(settings_file, "r") as fh:
                current = fh.read()
        except IOError as exc:
            module.fail_json(
                msg="Failed to read {0}: {1}".format(settings_file, exc)
            )
    else:
        current = None

    if current != new_content:
        changed = True

    report = {
        "file": settings_file,
        "previous_md5": None if current is None else _md5(current),
        "new_md5": _md5(new_content),
    }

    if changed and not module.check_mode:
        try:
            with open(settings_file, "w") as fh:
                fh.write(new_content)
        except IOError as exc:
            module.fail_json(
                msg="Failed to write {0}: {1}".format(settings_file, exc)
            )

    module.exit_json(
        changed=changed,
        message="Django settings applied to {0}".format(settings_file),
        report=report,
    )


def _md5(content):
    """Return an MD5 hex digest of the given string."""
    import hashlib

    return hashlib.md5(content.encode("utf-8")).hexdigest()


if __name__ == "__main__":
    main()